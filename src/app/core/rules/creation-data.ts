function weapon(
  name: string,
  group: string,
  encumbrance: number,
  reachOrRange: string,
  modifier: number,
  qualities: string[] = [],
  usesStrengthBonus = true,
): Weapon {
  return { name, group, encumbrance, reachOrRange, damage: { usesStrengthBonus, modifier }, qualities };
}

function armour(name: string, locations: Armour['locations'], encumbrance: number): Armour {
  return { name, locations, encumbrance, armourPoints: 1, qualities: [] };
}

